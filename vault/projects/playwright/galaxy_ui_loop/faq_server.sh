#!/usr/bin/env bash
# Local 26.2 Galaxy for the FAQ loop (HARDEN_AGAINST_FAQ.md), run from the galaxy_ui_driver worktree.
#
#   faq_server.sh start|stop|restart|status|env [PROFILE]
#
# Profiles (default: main):
#   main      port 8091, account activation off - most FAQs
#   accounts  port 8092, account activation on  - account FAQs (registration, activation mail)
#
# Each profile gets its own generated galaxy.yml and data dir (database, gravity state, captured
# mail) under ~/.cache/gxui-faq/server/PROFILE, so the worktree's config/ and database/ are untouched.
# start rebuilds the client only if client/ changed since the last build.
#
#   eval "$(galaxy_ui_loop/faq_server.sh env)"   # point gxui at the profile's server
set -euo pipefail

GALAXY_ROOT=${GALAXY_ROOT:-$HOME/projects/worktrees/galaxy/branch/galaxy_ui_driver}
FAQ_HOME=${FAQ_HOME:-$HOME/.cache/gxui-faq}
ADMIN_EMAIL=${FAQ_ADMIN_EMAIL:-jmchilton@gmail.com}

command=${1:-status}
profile=${2:-main}
case "$profile" in
    main) port=8091; activation=false ;;
    accounts) port=8092; activation=true ;;
    *) echo "unknown profile '$profile' (main, accounts)" >&2; exit 64 ;;
esac

state=$FAQ_HOME/server/$profile
config=$state/galaxy.yml
url=http://localhost:$port

write_config() {
    mkdir -p "$state"
    cat > "$config" <<EOF
# Generated by faq_server.sh - edits are overwritten on start.
gravity:
  gunicorn:
    bind: 127.0.0.1:$port
    preload: false
  celery:
    enable: false
    enable_beat: false
  gx_it_proxy:
    enable: false
  reports:
    enable: false
galaxy:
  data_dir: $state/data
  conda_auto_init: false
  admin_users: $ADMIN_EMAIL
  galaxy_infrastructure_url: $url
  user_activation_on: $activation
  smtp_server: mock_emails_to_path://$state/email.json
  smtp_ssl: false
  email_from: galaxy-faq@example.org
EOF
}

run_galaxy() {
    (cd "$GALAXY_ROOT" && GALAXY_CONFIG_FILE=$config GALAXY_LOG=$state/galaxy.log ./run.sh --skip-wheels "$@")
}

up() {
    curl -sf "$url/api/version" 2>/dev/null
}

case "$command" in
    start)
        if [ ! -d "$GALAXY_ROOT/.venv" ]; then
            echo "$GALAXY_ROOT has no .venv - bootstrap it first (/galaxy-bootstrap)" >&2
            exit 1
        fi
        if version=$(up); then
            echo "$profile already up at $url: $version"
            exit 0
        fi
        # run.sh skips this check in a worktree (.git is a file), so do it here.
        build_hash=$GALAXY_ROOT/static/client_build_hash.txt
        if [ ! -f "$build_hash" ] || ! git -C "$GALAXY_ROOT" diff --quiet "$(cat "$build_hash")" -- client/ config/plugins/visualizations/; then
            echo "client out of date - building (several minutes) ..."
            make -C "$GALAXY_ROOT" client-production
        fi
        write_config
        GALAXY_SKIP_CLIENT_BUILD=1 run_galaxy --daemon
        echo "waiting for $url (first start creates the database) ..."
        for _ in $(seq 1 180); do
            if version=$(up); then
                echo "$profile up at $url: $version"
                exit 0
            fi
            sleep 2
        done
        echo "$url not up after 6 minutes; see $state/data/gravity/log/" >&2
        exit 1
        ;;
    stop)
        [ -f "$config" ] && run_galaxy --stop-daemon
        ;;
    restart)
        "$0" stop "$profile"
        "$0" start "$profile"
        ;;
    status)
        if version=$(up); then echo "$profile up at $url: $version"; else echo "$profile down ($url)"; exit 3; fi
        ;;
    env)
        echo "export GXUI_PYTHON=$GALAXY_ROOT/.venv/bin/python"
        echo "export GXUI_HOME=$FAQ_HOME"
        echo "export GXUI_SESSION=$profile"
        echo "export GXUI_GALAXY_URL=$url"
        echo "export FAQ_MAIL=$state/email.json"
        ;;
    *)
        echo "usage: $0 start|stop|restart|status|env [main|accounts]" >&2
        exit 64
        ;;
esac
