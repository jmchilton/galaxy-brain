#!/usr/bin/env bash
# Local 26.2 Galaxy for the FAQ loop (HARDEN_AGAINST_FAQ.md), run from the galaxy_ui_driver worktree.
#
#   faq_server.sh start|stop|restart|status|env [PROFILE]
#
# Profiles (default: main):
#   main      port 8091 (FAQ_PORT overrides), account activation off - most FAQs
#   accounts  port 8092, account activation on  - account FAQs (registration, activation mail)
#
# Each profile gets its own generated galaxy.yml and data dir (database, gravity state, captured
# mail) under ~/.cache/gxui-faq/server/PROFILE, so the worktree's config/ and database/ are untouched.
# start rebuilds the client only if client/ changed since the last build.
# Interactive tools (Jupyter, RStudio) run in Docker behind gx-it-proxy on port+100, at
# <id>.interactivetool.localhost:PROXY_PORT; Docker must be running for them to launch.
#
#   eval "$(galaxy_ui_loop/faq_server.sh env)"   # point gxui at the profile's server
set -euo pipefail

GALAXY_ROOT=${GALAXY_ROOT:-$HOME/projects/worktrees/galaxy/branch/galaxy_ui_driver}
FAQ_HOME=${FAQ_HOME:-$HOME/.cache/gxui-faq}
ADMIN_EMAIL=${FAQ_ADMIN_EMAIL:-jmchilton@gmail.com}
# Replays that need an admin (e.g. to set up a data library) register or log in as this one.
REPLAY_ADMIN_EMAIL=faq-admin@example.org

command=${1:-status}
profile=${2:-main}
case "$profile" in
    main) port=${FAQ_PORT:-8091}; activation=false ;;
    accounts) port=${FAQ_PORT:-8092}; activation=true ;;
    *) echo "unknown profile '$profile' (main, accounts)" >&2; exit 64 ;;
esac

state=$FAQ_HOME/server/$profile
config=$state/galaxy.yml
url=http://localhost:$port
proxy_port=$((port + 100))

write_config() {
    mkdir -p "$state"
    cat > "$config" <<EOF
# Generated by faq_server.sh - edits are overwritten on start.
gravity:
  gunicorn:
    bind: 127.0.0.1:$port
    preload: false
  # Public servers run Celery; some UI (e.g. bulk Change data type) only shows with it.
  celery:
    enable: true
    enable_beat: false
  gx_it_proxy:
    enable: true
    port: $proxy_port
  reports:
    enable: false
galaxy:
  data_dir: $state/data
  conda_auto_init: false
  enable_celery_tasks: true
  admin_users: $ADMIN_EMAIL,$REPLAY_ADMIN_EMAIL
  galaxy_infrastructure_url: $url
  # Public servers offer remote file sources (Upload > Choose Remote Files) and GTN data libraries;
  # Galaxy's test-data stands in for both.
  file_sources_config_file: $state/file_sources_conf.yml
  library_import_dir: $GALAXY_ROOT/test-data
  # Lets Paste Links/URLs fetch this server's own Copy Link URLs, standing in for a second Galaxy.
  fetch_url_allowlist: 127.0.0.1,::1
  # FTP upload with no FTP server: replays copy files into \$FAQ_FTP/<email> in its place.
  ftp_upload_dir: $state/ftp
  ftp_upload_site: ftp.faq.example.org
  # Default tools, plus a sleep tool replays use to keep a job waiting (job status FAQ), a
  # two-version tool (tool version FAQ) and a shed tool conf for Admin tool installs.
  tool_config_file: $GALAXY_ROOT/lib/galaxy/config/sample/tool_conf.xml.sample,$state/shed_tool_conf.xml,$state/replay_tool_conf.xml,$state/interactive_tool_conf.xml
  # Every conf with a tool_path can take installs; the install form defaults to the first one.
  shed_tool_data_path: $state/shed_tool_data
  user_activation_on: $activation
  smtp_server: mock_emails_to_path://$state/email.json
  smtp_ssl: false
  email_from: galaxy-faq@example.org
  # Turns on dataset error reports; they land in the captured mail too.
  error_email_to: galaxy-errors@example.org
  # Interactive tools as on usegalaxy.*: Docker jobs, reached straight through gx-it-proxy.
  interactivetools_enable: true
  interactivetools_upstream_proxy: false
  interactivetools_proxy_host: localhost:$proxy_port
  interactivetools_map: $state/data/interactivetools_map.sqlite
  job_config_file: $state/job_conf.yml
  # Dockstore and WorkflowHub, as on usegalaxy.*; needs network.
  trs_servers_config_file: $state/trs_servers_conf.yml
EOF
    cat > "$state/job_conf.yml" <<EOF
runners:
  local:
    load: galaxy.jobs.runners.local:LocalJobRunner
    workers: 4
execution:
  default: local
  environments:
    local:
      runner: local
    docker:
      runner: local
      docker_enabled: true
      require_container: true
      # Jobs' PATH has no python; the monitor reports the IT's published port back to Galaxy.
      container_monitor_command: $GALAXY_ROOT/.venv/bin/python $GALAXY_ROOT/lib/galaxy_ext/container_monitor/monitor.py
      container_monitor_get_ip_method: 'command:echo 127.0.0.1'
tools:
  - id: interactive_tool_jupyter_notebook
    environment: docker
  - id: interactive_tool_rstudio
    environment: docker
EOF
    cat > "$state/file_sources_conf.yml" <<EOF
- type: posix
  id: test-data
  label: Galaxy test data
  doc: Galaxy's test-data directory
  root: $GALAXY_ROOT/test-data
  writable: false
# As on usegalaxy.org; needs network.
- type: s3fs
  label: Genome Ark
  id: genomeark
  doc: Access to Genome Ark open data on AWS.
  bucket: genomeark
  anon: true
EOF
    cat > "$state/trs_servers_conf.yml" <<EOF
- id: dockstore
  label: Dockstore
  link_url: https://dockstore.org
  api_url: https://dockstore.org/api
- id: workflowhub
  label: WorkflowHub
  link_url: https://workflowhub.eu
  api_url: https://workflowhub.eu
EOF
    cat > "$state/replay_tool_conf.xml" <<EOF
<toolbox tool_path="$GALAXY_ROOT/test/functional/tools">
  <section id="faq_replay" name="FAQ Replay">
    <tool file="cat_data_and_sleep.xml" />
    <tool file="multiple_versions_v01.xml" />
    <tool file="multiple_versions_v02.xml" />
  </section>
</toolbox>
EOF
    # Admin > Install and Uninstall installs here; kept across restarts so installs survive.
    [ -f "$state/shed_tool_conf.xml" ] || cat > "$state/shed_tool_conf.xml" <<EOF
<toolbox tool_path="$state/shed_tools">
</toolbox>
EOF
    cat > "$state/interactive_tool_conf.xml" <<EOF
<toolbox tool_path="$GALAXY_ROOT/tools/interactive">
  <section id="interactivetools" name="Interactive Tools">
    <tool file="interactivetool_jupyter_notebook.xml" />
    <tool file="interactivetool_rstudio.xml" />
  </section>
</toolbox>
EOF
}

# Command-line tools that converters (Datatypes > Convert) need, on the jobs' PATH. Public servers
# resolve them per tool; bioconda lacks osx-arm64 builds of some pinned versions, so use one env.
TOOL_DEPS=(samtools)
tool_deps=$FAQ_HOME/tool_deps
CONDA=${FAQ_CONDA:-$HOME/miniforge3/bin/conda}

ensure_tool_deps() {
    if [ ! -x "$tool_deps/bin/${TOOL_DEPS[0]}" ]; then
        echo "creating $tool_deps with ${TOOL_DEPS[*]} ..."
        "$CONDA" create -y -q -p "$tool_deps" -c conda-forge -c bioconda "${TOOL_DEPS[@]}"
    fi
}

run_galaxy() {
    (cd "$GALAXY_ROOT" && PATH=$tool_deps/bin:$PATH GALAXY_CONFIG_FILE=$config GALAXY_LOG=$state/galaxy.log ./run.sh --skip-wheels "$@")
}

up() {
    curl -sf "$url/api/version" 2>/dev/null
}

case "$command" in
    start)
        if [ ! -d "$GALAXY_ROOT/.venv" ]; then
            echo "$GALAXY_ROOT has no .venv - bootstrap it first (/galaxy-bootstrap)" >&2
            exit 1
        fi
        if version=$(up); then
            echo "$profile already up at $url: $version"
            exit 0
        fi
        # run.sh skips this check in a worktree (.git is a file), so do it here. navigation.yml is
        # only read by tests and gxui, so editing it needs no rebuild.
        build_hash=$GALAXY_ROOT/static/client_build_hash.txt
        if [ ! -f "$build_hash" ] || ! git -C "$GALAXY_ROOT" diff --quiet "$(cat "$build_hash")" -- client/ config/plugins/visualizations/ ':!client/src/utils/navigation/navigation.yml'; then
            echo "client out of date - building (several minutes) ..."
            make -C "$GALAXY_ROOT" client-production
        fi
        ensure_tool_deps
        write_config
        GALAXY_SKIP_CLIENT_BUILD=1 run_galaxy --daemon
        echo "waiting for $url (first start creates the database) ..."
        for _ in $(seq 1 180); do
            if version=$(up); then
                echo "$profile up at $url: $version"
                exit 0
            fi
            sleep 2
        done
        echo "$url not up after 6 minutes; see $state/data/gravity/log/" >&2
        exit 1
        ;;
    stop)
        [ -f "$config" ] && run_galaxy --stop-daemon
        ;;
    restart)
        "$0" stop "$profile"
        "$0" start "$profile"
        ;;
    status)
        if version=$(up); then echo "$profile up at $url: $version"; else echo "$profile down ($url)"; exit 3; fi
        ;;
    env)
        echo "export GXUI_PYTHON=$GALAXY_ROOT/.venv/bin/python"
        echo "export GXUI_GALAXY_ROOT=$GALAXY_ROOT"
        echo "export GXUI_HOME=$FAQ_HOME"
        echo "export GXUI_SESSION=$profile"
        echo "export GXUI_GALAXY_URL=$url"
        echo "export FAQ_MAIL=$state/email.json"
        echo "export FAQ_FTP=$state/ftp"
        ;;
    *)
        echo "usage: $0 start|stop|restart|status|env [main|accounts]" >&2
        exit 64
        ;;
esac
